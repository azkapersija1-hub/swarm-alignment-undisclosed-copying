"""Generate Markdown tables (with 95% cluster-bootstrap CIs) from the metrics CSVs for the report writers. English."""
import csv
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MET = os.path.join(ROOT, "07_STATISTICAL_ANALYSIS")
KEY = ["F0a report rule (same cited source)", "F0b LLM report-only", "D  LLM with sources (Config D)", "F1 lexical 3-gram", "F2 embedding cosine", "F3 STP",
       "F4 STP-AR", "F5 STP-AR+MOI", "F6 RCC-v3.3 (AR)", "F6b RCC-v3.3 (AR+MOI)", "F8a Argon embedding triage", "F8b Argon claim overlap",
       "S1 claim unsupported by cited source", "S2 source containment (twin/near)", "F9 formula ensemble (artifact only)", "F9b ensemble + source checks",
       "P  ledger only [full]", "F10 ensemble + ledger [full]", "F10 ensemble + ledger [comm_hidden]", "F10 ensemble + ledger [half]", "F10 ensemble + ledger [none]"]
TNAME = {"copy": "Target A - copying occurred", "noninde": "Target B - evidence non-independent", "provfalse": "Target C - provenance claim false"}


def fm(r, k, ci=True):
    v = float(r[k])
    if v != v:
        return "n/a"
    if ci and (k + "_lo") in r and r[k + "_lo"] not in ("", "nan"):
        return "%.3f [%.3f, %.3f]" % (v, float(r[k + "_lo"]), float(r[k + "_hi"]))
    return "%.3f" % v


def table(rows, target, rule):
    out = ["| Monitor | Recall | FPR | Precision | F1 | MCC | AUROC | AUPRC | Brier | BSS |", "|---|---|---|---|---|---|---|---|---|---|"]
    for m in KEY:
        r = next((x for x in rows if x["monitor"] == m and x["target"] == target and x["threshold_rule"] == rule), None)
        if r:
            out.append("| %s | %s | %s | %s | %.3f | %.3f | %s | %.3f | %s | %.3f |" % (m.strip(), fm(r, "recall"), fm(r, "fpr"), fm(r, "precision", False),
                       float(r["f1"]) if r["f1"] != "nan" else float("nan"), float(r["mcc"]), fm(r, "auroc"), float(r["auprc"]), fm(r, "brier"), float(r["bss"])))
    return out


def main():
    out = ["# TABLES (generated by src/make_tables.py from the metrics CSVs; do not edit by hand)", "",
           "CI = 95% cluster-bootstrap (clusters = replicate x base source of agent A; 1000 resamples; 200 for the naive threshold rule). "
           "Descriptive statistics only. BSS = 1 - Brier / Brier of a constant predictor using the calibration prevalence.", ""]
    for tag, title in (("metrics_tls_alllabels", "PRIMARY: all scenarios, ground truth from the controller's design"),
                       ("metrics_tls", "SENSITIVITY: only copy scenarios whose copying was verified by reused numbers (others excluded as unknown label)")):
        p = os.path.join(MET, tag, "results_main.csv")
        if not os.path.isfile(p):
            continue
        rows = list(csv.DictReader(open(p, encoding="utf-8")))
        n = {t: next(r for r in rows if r["target"] == t and r["monitor"].startswith("F4")) for t in TNAME}
        out += ["## %s" % title, ""]
        for t, name in TNAME.items():
            out += ["### %s (pooled test n = %s, positives = %s)" % (name, n[t]["n"], n[t]["n_pos"]), "", "Threshold = 95th percentile of ALL calibration negatives of this target (honest twins included).", ""]
            out += table(rows, t, "all") + [""]
        out += ["### Naive threshold (calibrated on independent-source negatives only), Target A", ""] + table(rows, "copy", "ind") + [""]
    ptype = os.path.join(MET, "metrics_tls_alllabels", "results_per_type.csv")
    if os.path.isfile(ptype):
        rows = list(csv.DictReader(open(ptype, encoding="utf-8")))
        types = ["IND_SAME", "IND_DIFF", "NOSRC_SAME", "TWIN_H", "NEAR_H", "SHARED_OK", "COPY_LIT", "COPY_PARA", "COPY_TWIN", "COPY_COVER"]
        out += ["## Flag rate by scenario type (PRIMARY, Target A threshold)", "", "| Monitor | " + " | ".join(types) + " |", "|---|" + "---|" * len(types)]
        for m in KEY:
            vals = []
            for t in types:
                r = next((x for x in rows if x["monitor"] == m and x["target"] == "copy" and x["type"] == t), None)
                vals.append("%.2f" % float(r["flag_rate"]) if r else "-")
            out.append("| %s | %s |" % (m.strip(), " | ".join(vals)))
    open(os.path.join(MET, "TABLES.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("tables written", len(out), "lines")


if __name__ == "__main__":
    main()
